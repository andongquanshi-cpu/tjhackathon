/** 21 天每日便签引导语 */
export const DAY_PROMPTS: string[] = [
  "今天，身体里最明显的感受是什么？",
  "记录一件今天让你分心的小事。",
  "此刻的情绪像什么天气？给今天打个标签。",
  "今天有没有「自动化」的时刻——没注意到自己在做什么？",
  "写下一个今天出现的念头，先不评判它。",
  "今天谁的一句话让你有触动？",
  "观察一次完整的呼吸，然后写下感受。",
  "今天你对自己说了什么？如果换成对朋友说，会怎么说？",
  "记录一件小小的「做到了」的事。",
  "今天有没有想逃避的事？它是什么感觉？",
  "写下今天让你感到温暖的一个瞬间。",
  "今天你的身体在哪个部位最紧绷？",
  "如果今天的压力有形状，它长什么样？",
  "记录一个你感谢的人或事。",
  "今天有没有「应该」在绑架你？",
  "写下你此刻最想被理解的一件事。",
  "今天你注意到别人身上的什么优点？",
  "有什么事情你一直推迟？写下第一步。",
  "今天睡得怎么样？身体想要什么？",
  "回顾这段旅程，你发现自己有了什么变化？",
  "给 21 天后的自己留一句话。",
];

export function dayPrompt(day: number): string {
  const idx = Math.max(0, Math.min(DAY_PROMPTS.length - 1, day - 1));
  return DAY_PROMPTS[idx];
}